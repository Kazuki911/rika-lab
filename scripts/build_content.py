import json, pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
TOPICS=[]
def topic(id,title,unit,grade,field,pairs,quiz,data,model,inquiry):
    # pairs: term=definition; quiz: prompt|correct|distractor|distractor|explanation
    parsed_pairs=[x.split('=',1) for x in pairs.split(';')]
    parsed_quiz=[]
    for line in quiz.strip().split('\n'):
        q,a,b,c,why=line.split('|');parsed_quiz.append({'prompt':q,'options':[a,b,c],'correct':0,'explanation':why})
    TOPICS.append(dict(id=id,title=title,unit=unit,grade=grade,field=field,pairs=parsed_pairs,quiz=parsed_quiz,data=data,model=model,inquiry=inquiry))
def table(title,headers,rows,qs,note='学習用に作成した仮想データです。実測値ではありません。'):
    questions=[]
    for q,a,b,c,why in qs:questions.append(dict(prompt=q,options=[a,b,c],correct=0,explanation=why))
    return dict(title=title,headers=headers,rows=rows,questions=questions,note=note)
def calc(key,title,controls,formula,note,goal,advanced=False):return dict(kind='calc',key=key,title=title,controls=controls,formula=formula,note=note,goal=goal,advanced=advanced)
def flow(title,steps,note,goal):return dict(kind='flow',title=title,steps=[x.split('=',1) for x in steps.split(';')],note=note,goal=goal,advanced=False)
def c(key,label,lo,hi,step,value,unit):return [key,label,lo,hi,step,value,unit]
